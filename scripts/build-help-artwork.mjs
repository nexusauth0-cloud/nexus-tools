// Bundles every tool module once, lets their decorators register ASCII art,
// and writes a committed snapshot module (src/lib/registry/generated/help-artwork.ts)
// so the printing feature never imports tool modules at runtime.
//
// Usage: node scripts/build-help-artwork.mjs
// Fails (exit 1) if a static tool entry point is missing its art.

import { build } from "esbuild"
import { writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const OUTPUT = resolve(ROOT, "node_modules/.cache/help-artwork-bundle.mjs")
const SNAPSHOT = resolve(ROOT, "src/lib/registry/generated/help-artwork.ts")

await build({
  entryPoints: [resolve(ROOT, "src/lib/registry/artwork-bundle.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  outfile: OUTPUT,
  logLevel: "silent",
  external: ["esbuild", "js-yaml", "json5"],
})

const printed = execFileSync(process.execPath, [OUTPUT], { encoding: "utf8" })
const registered = JSON.parse(printed)

if (typeof registered !== "object" || Object.keys(registered).length === 0) {
  console.error("build-help-artwork: no decorations registered; run() must print JSON.")
  process.exit(1)
}

const source = `// GENERATED by scripts/build-help-artwork.mjs — do not edit by hand.
// Snapshot of all registered tool decorations (for the printing feature).
export const HELP_ARTWORK: Record<string, string> = ${JSON.stringify(registered, null, 2)}
`
mkdirSync(dirname(SNAPSHOT), { recursive: true })
writeFileSync(SNAPSHOT, source)
console.log(`build-help-artwork: wrote ${Object.keys(registered).length} decorations to ${SNAPSHOT}`)