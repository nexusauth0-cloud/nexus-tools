/**
 * Deterministic image byte fixtures for unit tests.
 *
 * These are hand-built headers (no real pixel payloads) — enough for the
 * magic-byte probing, dimension parsing, validation and EXIF layers while
 * staying tiny and stable.
 */
export function pngBytes(width: number, height: number): Uint8Array {
  const bytes = new Uint8Array(65)
  bytes.set([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  bytes.set([0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52], 8)
  bytes[16] = (width >>> 24) & 0xff
  bytes[17] = (width >>> 16) & 0xff
  bytes[18] = (width >>> 8) & 0xff
  bytes[19] = width & 0xff
  bytes[20] = (height >>> 24) & 0xff
  bytes[21] = (height >>> 16) & 0xff
  bytes[22] = (height >>> 8) & 0xff
  bytes[23] = height & 0xff
  bytes[24] = 8
  bytes[25] = 6
  bytes.set([0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82], 53)
  return bytes
}

