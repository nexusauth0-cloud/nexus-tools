export function webpBytes(width: number, height: number): Uint8Array {
  const bytes = new Uint8Array(30)
  bytes.set([0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50], 0)
  bytes.set([0x56, 0x50, 0x38, 0x58, 0x0a, 0x00, 0x00, 0x00], 12)
  const w = width - 1
  const h = height - 1
  bytes[21] = w & 0xff
  bytes[22] = (w >>> 8) & 0xff
  bytes[23] = (w >>> 16) & 0xff
  bytes[24] = h & 0xff
  bytes[25] = (h >>> 8) & 0xff
  bytes[26] = (h >>> 16) & 0xff
  return bytes
}

export function minimalAvif(): Uint8Array {
  const bytes = new Uint8Array(40)
  bytes.set([0x00, 0x00, 0x00, 0x18, 0x66, 0x74, 0x79, 0x70], 0)
  bytes.set([0x61, 0x76, 0x69, 0x66, 0x00, 0x00, 0x00, 0x00, 0x61, 0x76, 0x69, 0x66], 8)
  return bytes
}
