const FALLBACK_ICON: LucideIcon = Sparkles

/**
 * Resolve an icon name to its Lucide component.
 * Safe to call from both Server and Client components — components are
 * never transmitted across the boundary, only `IconName` strings are.
 */
export function resolveIcon(name?: IconName | null): LucideIcon {
  if (name && name in iconRegistry) return iconRegistry[name]
  return FALLBACK_ICON
}

/** All icon names available to tool manifests. */
export const availableIconNames: readonly IconName[] = iconNames
